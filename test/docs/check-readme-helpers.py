#!/usr/bin/env python3
"""Every `%%helper` a Toy README names must still be defined in that chapter's sources.

Names generated by define-dialect (`%%toy:initialize`, `%%toy-iface-init`, ...) are not in the sources."""
import pathlib
import re
import sys

toy = pathlib.Path(sys.argv[1])
bad = []
for readme in sorted(toy.glob("ch*/README.md")):
    sources = "\n".join(p.read_text() for p in readme.parent.glob("*.sls"))
    for name in sorted(set(re.findall(r"`(%%[^\s`]+)`", readme.read_text()))):
        if name.startswith("%%toy"):
            continue
        if not re.search(r"\(define[\w-]* \(?" + re.escape(name) + r"[\s)]", sources):
            bad.append(f"{readme}: `{name}` is not defined in {readme.parent.name}/*.sls")
if bad:
    print("\n".join(bad))
    sys.exit(1)
